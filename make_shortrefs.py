#!/usr/bin/env python3
"""Generate brief citation strings for footnotes from references.bib."""
import re
from pathlib import Path

import sys
bib = sys.argv[1] if len(sys.argv) > 1 else "ref.bib"
out_path = sys.argv[2] if len(sys.argv) > 2 else "shortrefs.tex"
text = Path(bib).read_text()
entries = re.split(r"\n@", "\n" + text)
out = ["% Generated by make_shortrefs.py; do not edit by hand.\n"]
for entry in entries:
    m = re.match(r"\s*(\w+)\s*\{\s*([^,]+),", entry)
    if not m:
        continue
    key = m.group(2).strip()
    fields = {}
    for name in ("author", "title", "year", "booktitle", "journal"):
        fm = re.search(rf"\b{name}\s*=\s*\{{(.*?)\}}\s*,?\s*\n", entry, re.S)
        if fm:
            fields[name] = " ".join(fm.group(1).split()).replace("{", "").replace("}", "")
    if "author" not in fields or "title" not in fields or "year" not in fields:
        continue
    authors = [a.strip() for a in fields["author"].split(" and ") if a.strip()]
    first = authors[0].split(",")[0].strip()
    who = f"{first} et al." if len(authors) > 1 else first
    venue = fields.get("booktitle", fields.get("journal", "")).strip()
    pieces = [f"{who} ({fields['year']})", f"\\textcolor{{NJUPurple}}{{\\emph{{{fields['title']}}}}}" ]
    if venue:
        pieces.append(venue)
    short = ", ".join(pieces) + "."
    out.append(f"\\expandafter\\def\\csname shortref@{key}\\endcsname{{{short}}}\n")
Path(out_path).write_text("".join(out))
